	/**
	 * One rule as an associative array, or null.
	 *
	 * @param string $code Finding code.
	 * @return array{group:string, severity:string, title:string, why:string, fix:string}|null
	 */
	public static function get( string $code ): ?array {
		$rules = self::rules();

		if ( ! isset( $rules[ $code ] ) ) {
			return null;
		}

		list( $group, $severity, $title, $why, $fix ) = $rules[ $code ];

		return compact( 'group', 'severity', 'title', 'why', 'fix' );
	}
