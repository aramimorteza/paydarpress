	/**
	 * Labels for select fields.
	 *
	 * @return array<string, string>
	 */
	public static function labels(): array {
		return array_map( static fn( $i ) => $i['label'], self::all() );
	}

	/**
	 * Industries for the UI: labels, defaults and examples (keywords are server-side only).
	 */
	public static function for_ui(): array {
		$out     = array();
		$default = self::all()[ self::DEFAULT_EXAMPLE ]['ex'];
		foreach ( self::all() as $key => $industry ) {
			$out[ $key ] = array(
				'label'     => $industry['label'],
				'ymyl'      => $industry['ymyl'],
				'goal'      => $industry['goal'],
				'knowledge' => $industry['knowledge'],
				'rules'     => $industry['rules'],
				'patterns'  => $industry['patterns'],
				'ex'        => $industry['ex'] + $default,
			);
		}

		return $out;
	}

	/**
	 * Detects the industry from normalised site text. Checked in registry order, except that
	 * WooCommerce sites without a clearer match are treated as online shops.
	 *
	 * @param string $haystack    Normalised site name, tagline and category names.
	 * @param bool   $woocommerce Whether WooCommerce is active.
	 */
	public static function detect( string $haystack, bool $woocommerce ): string {
		$scores = array();
		foreach ( self::all() as $key => $industry ) {
			$hits = 0;
			foreach ( $industry['keywords'] as $word ) {
				if ( '' !== $word && false !== mb_stripos( $haystack, \PaydarWP\PaydarPress\Text\PersianNormalizer::normalize( $word ) ) ) {
					++$hits;
				}
			}
			if ( $hits > 0 ) {
				$scores[ $key ] = $hits;
			}
		}

		// Generic shop words lose against a specific industry with the same number of hits.
		if ( isset( $scores['ecommerce-retail'] ) && count( $scores ) > 1 ) {
			$scores['ecommerce-retail'] -= 0.5;
		}

		if ( array() !== $scores ) {
			arsort( $scores );
			return (string) array_key_first( $scores );
		}

		return $woocommerce ? 'ecommerce-retail' : 'custom';
	}
