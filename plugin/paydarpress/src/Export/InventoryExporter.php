<?php
/**
 * Builds the site inventory JSON for ContentMaster (schema 1.0, profile contentmaster-lite).
 *
 * @package PaydarPress
 */

declare(strict_types=1);

namespace PaydarWP\PaydarPress\Export;

use PaydarWP\PaydarPress\Audit\AuditEngine;
use PaydarWP\PaydarPress\Core\Activity;
use PaydarWP\PaydarPress\Database\Schema;
use PaydarWP\PaydarPress\Gsc\GscRepository;
use PaydarWP\PaydarPress\Profile\Fields;
use PaydarWP\PaydarPress\Profile\ProfileRepository;
use PaydarWP\PaydarPress\Scanner\ContentScanner;
use PaydarWP\PaydarPress\Scanner\MenuScanner;
use PaydarWP\PaydarPress\Seo\SeoDetector;
use PaydarWP\PaydarPress\Text\PersianNormalizer;
use RuntimeException;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Spec section 12 and architecture section 10. The export never contains emails, user names,
 * comments, user data or keys. Files live in a protected uploads folder and expire after 24h.
 */
final class InventoryExporter {

	public const SCHEMA_VERSION = '1.0';
	public const OPTION_LAST    = 'paydarpress_last_export';
	public const TTL            = DAY_IN_SECONDS;

	/**
	 * Files are stored as .php starting with this guard, so a direct request executes it and
	 * returns nothing even on servers that ignore .htaccess (nginx, LiteSpeed configs, IIS).
	 */
	public const GUARD = "<?php exit; ?>\n";

	/** Above this many posts+products the UI suggests the compact format. */
	public const COMPACT_SUGGEST_AT = 300;

	/** @var bool Compact format: fewer fields per item, for large sites and small AI context windows. */
	private bool $compact = false;

	/** @var array<int, array>|null Search Console metrics per content ID (null without imported data). */
	private ?array $gsc = null;

	/**
	 * Builds the export array.
	 *
	 * @param bool $include_drafts Include unpublished content.
	 * @param bool $compact        Compact format (no outline/excerpt/SEO title/meta, empty fields omitted).
	 */
	public function build( bool $include_drafts = false, bool $compact = false ): array {
		$this->compact = $compact;
		$this->gsc     = GscRepository::has_data() ? GscRepository::page_metrics() : null;
		$profile    = ProfileRepository::get();
		$completion = ProfileRepository::completion( $profile );
		$statuses   = $include_drafts ? ContentScanner::STATUSES : array( 'publish' );
		$rows       = $this->rows( $statuses );
		$flags      = $this->flags();
		$menu_ids   = $this->main_menu_page_ids();
		$key_pages  = array_flip( ProfileRepository::key_page_ids() );

		$pages    = array();
		$posts    = array();
		$products = array();

		foreach ( $rows as $row ) {
			$id = (int) $row['object_id'];

			if ( 'page' === $row['object_type'] ) {
				$pages[] = array(
					'id'            => $id,
					'title'         => $this->title( $id ),
					'slug'          => rawurldecode( (string) get_post_field( 'post_name', $id ) ),
					'url'           => $row['url'],
					'status'        => $row['status'],
					'in_main_menu'  => isset( $menu_ids[ $id ] ),
					'is_front_page' => (int) get_option( 'page_on_front' ) === $id,
					'is_key_page'   => isset( $key_pages[ $id ] ),
					'flags'         => $flags[ $id ] ?? array(),
				);
				if ( null !== $this->gsc ) {
					$pages[ count( $pages ) - 1 ]['search_console'] = $this->gsc_item( $id );
				}
				if ( $compact ) {
					unset( $pages[ count( $pages ) - 1 ]['slug'] );
				}
				continue;
			}

			$item = $this->content_item( $row, $flags[ $id ] ?? array() );

			if ( 'product' === $row['object_type'] ) {
				$products[] = $item;
			} else {
				$posts[] = $item;
			}
		}

		$stats    = get_option( AuditEngine::OPTION_STATS, array() );
		$warnings = $this->warnings( $completion );

		$data = array(
			'export_meta'   => array(
				'schema_version'      => self::SCHEMA_VERSION,
				'generator'           => 'PaydarPress ' . PAYDARPRESS_VERSION,
				'generated_at'        => gmdate( 'c' ),
				'export_profile'      => $compact ? 'contentmaster-compact' : 'contentmaster-lite',
				'sections'            => array_merge( array( 'site', 'profile', 'taxonomies', 'pages', 'posts', 'products', 'stats', 'warnings' ), null === $this->gsc ? array() : array( 'search_console' ) ),
				'part'                => 1,
				'total_parts'         => 1,
				'include_drafts'      => $include_drafts,
				'seo_plugin'          => SeoDetector::adapter()->key(),
				'page_builder'        => $profile['fields']['page_builder']['value'] ?? '',
				'multilingual_plugin' => null,
				'instructions'        => 'This file was generated by the PaydarPress WordPress plugin for AI content assistants. Use `profile` as the SITE PROFILE, `posts`/`pages`/`products` as the CONTENT INVENTORY, and ask the user only about `profile.missing_fields`.' . ( $compact ? ' Compact format: items keep only id, title, url, date, category, focus keyword, word count, link counts, refresh score and flags; missing keys mean empty, false or zero.' : '' ),
			),
			'site'          => array(
				'name'                => html_entity_decode( get_bloginfo( 'name' ), ENT_QUOTES, 'UTF-8' ),
				'url'                 => home_url( '/' ),
				'tagline'             => html_entity_decode( get_bloginfo( 'description' ), ENT_QUOTES, 'UTF-8' ),
				'language'            => get_locale(),
				'timezone'            => wp_timezone_string(),
				'permalink_structure' => (string) get_option( 'permalink_structure' ),
				'wordpress_version'   => get_bloginfo( 'version' ),
				'woocommerce'         => class_exists( 'WooCommerce' ),
				'scanned_post_types'  => ContentScanner::post_types(),
				// Writing rules ContentMaster must follow (slug style, image ratios and counts).
				'content_rules'       => array(
					'policy'  => array(
						'slug_style' => (string) \PaydarWP\PaydarPress\Core\Settings::get( 'policy.slug_style', 'english' ),
					),
					'images'  => array(
						'featured_ratio'   => (string) \PaydarWP\PaydarPress\Core\Settings::get( 'images.featured_ratio', '16:9' ),
						'inline_ratio'     => (string) \PaydarWP\PaydarPress\Core\Settings::get( 'images.inline_ratio', '4:3' ),
						'words_per_inline' => (int) \PaydarWP\PaydarPress\Core\Settings::get( 'images.words_per_inline', 400 ),
						'inline_max'       => (int) \PaydarWP\PaydarPress\Core\Settings::get( 'images.inline_max', 5 ),
					),
				),
			),
			'profile'       => $this->profile( $profile, $completion ),
			'taxonomies'    => $this->taxonomies(),
			'pages'         => $pages,
			'posts'         => $posts,
			'products'      => $products,
			'stats'         => array(
				'posts'             => count( $posts ),
				'pages'             => count( $pages ),
				'products'          => count( $products ),
				'health_score'      => $stats['health_score'] ?? null,
				'findings_by_level' => $stats['by_severity'] ?? null,
				'findings_by_code'  => $stats['by_code'] ?? null,
				'orphans'           => $stats['orphans'] ?? null,
				'refresh_candidates' => $stats['refresh'] ?? null,
				'audited_at'        => $stats['audited_at'] ?? null,
			),
			'warnings'      => $warnings,
			'data_coverage' => array(
				'seo_metadata'   => 'none' === SeoDetector::adapter()->key() ? 'unavailable' : 'full',
				'full_content'   => 'excluded',
				'item_detail'    => $compact ? 'compact' : 'full',
				'link_graph'     => 'summary',
				'media'          => 'summary',
				'search_console' => null === $this->gsc ? 'not_connected' : 'csv_import',
			),
		);

		if ( null !== $this->gsc ) {
			$data['search_console'] = $this->search_console_section();
		}

		// Topics already imported from ContentMaster, so new topic lists do not repeat them.
		$topics = array_values(
			array_filter(
				\PaydarWP\PaydarPress\Import\TopicRepository::all_titles(),
				static fn( $t ) => 'written' !== $t['status']
			)
		);
		if ( array() !== $topics ) {
			$data['suggested_topics'] = array_map(
				static fn( $t ) => $compact ? array( $t['title'], $t['status'] ) : array(
					'title'  => $t['title'],
					'status' => $t['status'],
				),
				array_slice( $topics, 0, 300 )
			);
		}

		return $data;
	}

	/**
	 * Builds the export and writes it to a protected file.
	 *
	 * @param bool $include_drafts Include unpublished content.
	 * @param bool $compact        Compact format.
	 * @return array Export info (also stored in OPTION_LAST).
	 * @throws RuntimeException When the file cannot be written.
	 */
	public function create_file( bool $include_drafts = false, bool $compact = false ): array {
		$data = $this->build( $include_drafts, $compact );
		// No pretty-printing: whitespace costs AI tokens and the file is read by a model, not a person.
		$json = wp_json_encode( $data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES );

		if ( false === $json ) {
			throw new RuntimeException( 'ساخت فایل JSON ناموفق بود.' );
		}

		$dir = self::directory();
		self::delete_previous();

		$token = wp_generate_password( 32, false, false );
		$path  = $dir . $token . '.php';

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
		if ( false === file_put_contents( $path, self::GUARD . $json ) ) {
			throw new RuntimeException( 'نوشتن فایل خروجی در پوشه آپلود ممکن نشد. دسترسی نوشتن پوشه uploads را بررسی کنید.' );
		}

		$domain = (string) preg_replace( '/[^a-z0-9.\-]/i', '', (string) wp_parse_url( home_url(), PHP_URL_HOST ) );
		$info   = array(
			'token'      => $token,
			'filename'   => sprintf( 'paydarpress-%s-%s.json', $domain, gmdate( 'Y-m-d' ) ),
			'size'       => strlen( $json ),
			'created_at' => gmdate( 'c' ),
			'counts'     => $data['stats'],
			'drafts'     => $include_drafts,
			'compact'    => $compact,
			'missing'    => $data['profile']['missing_fields'],
		);

		update_option( self::OPTION_LAST, $info, false );

		Activity::log( 'export.created', sprintf( 'خروجی JSON سایت ساخته شد (%s نوشته، %s برگه%s).', PersianNormalizer::fa_number( count( $data['posts'] ) ), PersianNormalizer::fa_number( count( $data['pages'] ) ), $compact ? '، فشرده' : '' ), 'export', 0 );

		return $info;
	}

	/**
	 * Path of the last export file if it exists and has not expired.
	 *
	 * @param string $token Token.
	 */
	public static function file_for( string $token ): ?string {
		$last = get_option( self::OPTION_LAST, array() );

		if ( ! is_array( $last ) || empty( $last['token'] ) || ! hash_equals( (string) $last['token'], $token ) ) {
			return null;
		}

		if ( strtotime( (string) $last['created_at'] ) < time() - self::TTL ) {
			return null;
		}

		$path = self::directory() . $last['token'] . '.php';

		return file_exists( $path ) ? $path : null;
	}

	/**
	 * Deletes expired export files.
	 */
	public static function cleanup(): void {
		$dir = self::directory( false );
		if ( '' === $dir ) {
			return;
		}

		// Two globs instead of GLOB_BRACE, which is unavailable on some systems (musl).
		foreach ( array_merge( (array) glob( $dir . '*.json' ), (array) glob( $dir . '*.php' ) ) as $file ) {
			if ( is_string( $file ) && 'index.php' === basename( $file ) ) {
				continue;
			}
			if ( is_string( $file ) && filemtime( $file ) < time() - self::TTL ) {
				wp_delete_file( $file );
			}
		}
	}

	/**
	 * Protected export folder (created on demand).
	 *
	 * @param bool $create Create if missing.
	 * @throws RuntimeException When the folder cannot be created.
	 */
	public static function directory( bool $create = true ): string {
		$uploads = wp_upload_dir( null, false );
		$dir     = trailingslashit( $uploads['basedir'] ) . 'paydarpress/exports/';

		if ( ! is_dir( $dir ) ) {
			if ( ! $create ) {
				return '';
			}
			if ( ! wp_mkdir_p( $dir ) ) {
				throw new RuntimeException( 'ساخت پوشه خروجی در uploads ممکن نشد.' );
			}
		}

		// Block direct web access (Apache/LiteSpeed; IIS) and directory listing.
		$guards = array(
			'.htaccess'  => "Require all denied\nDeny from all\n",
			'index.php'  => "<?php\n// Silence is golden.\n",
			'web.config' => '<?xml version="1.0" encoding="UTF-8"?><configuration><system.webServer><authorization><deny users="*" /></authorization></system.webServer></configuration>',
		);
		foreach ( $guards as $name => $content ) {
			if ( ! file_exists( $dir . $name ) ) {
				// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
				file_put_contents( $dir . $name, $content );
			}
		}

		return $dir;
	}

	/**
	 * Removes the previous export file.
	 */
	private static function delete_previous(): void {
		$last = get_option( self::OPTION_LAST, array() );
		if ( is_array( $last ) && ! empty( $last['token'] ) ) {
			$path = self::directory( false ) . $last['token'] . '.php';
			if ( '' !== self::directory( false ) && file_exists( $path ) ) {
				wp_delete_file( $path );
			}
		}
	}

	/**
	 * Profile section: value/source/confirmed per field plus missing fields.
	 *
	 * @param array $profile    Profile.
	 * @param array $completion Completion.
	 */
	private function profile( array $profile, array $completion ): array {
		$out = array();
		foreach ( Fields::all() as $name => $def ) {
			$field        = $profile['fields'][ $name ];
			$out[ $name ] = array(
				'label'     => $def['label'],
				'value'     => $field['value'],
				'source'    => $field['source'],
				'confirmed' => (bool) $field['confirmed'],
			);
		}

		// Category names next to ids, so ContentMaster can match "link from these categories".
		if ( is_array( $out['key_pages']['value'] ?? null ) ) {
			foreach ( $out['key_pages']['value'] as &$page ) {
				$page['link_categories_names'] = array_values( array_filter( array_map( static fn( $c ) => ( $t = get_term( (int) $c, 'category' ) ) && ! is_wp_error( $t ) ? html_entity_decode( $t->name, ENT_QUOTES, 'UTF-8' ) : '', (array) ( $page['link_categories'] ?? array() ) ) ) );
			}
			unset( $page );
		}

		$stats              = \PaydarWP\PaydarPress\Links\KeyPageLinks::stats();
		$out['link_rules']  = array(
			'max_key_page_links_per_article' => \PaydarWP\PaydarPress\Links\KeyPageLinks::MAX_PER_ARTICLE,
			'exact_anchor_max_share'         => \PaydarWP\PaydarPress\Links\KeyPageLinks::EXACT_CAP,
			'key_page_anchor_stats'          => array_values(
				array_map(
					static fn( $st ) => array(
						'id'          => $st['id'],
						'main_phrase' => $st['main_phrase'],
						'links'       => $st['total'],
						'exact_share' => $st['exact_share'],
						'over_cap'    => $st['over_cap'],
						'counts'      => $st['counts'],
					),
					$stats
				)
			),
		);

		$out['missing_fields']        = $completion['missing'];
		$out['completion_percent']    = $completion['percent'];
		$industry                     = \PaydarWP\PaydarPress\Profile\Industries::all()[ $profile['fields']['industry_module']['value'] ] ?? null;
		$out['industry_module_label'] = $industry['label'] ?? '';
		$out['industry_ymyl']         = (bool) ( $industry['ymyl'] ?? false );

		return $out;
	}

	/**
	 * One post or product.
	 *
	 * @param array    $row   Inventory row.
	 * @param string[] $flags Open finding codes.
	 */
	private function content_item( array $row, array $flags ): array {
		$id         = (int) $row['object_id'];
		$is_product = 'product' === $row['object_type'];
		$cat_tax    = $is_product ? 'product_cat' : 'category';
		$tag_tax    = $is_product ? 'product_tag' : 'post_tag';
		$categories = taxonomy_exists( $cat_tax ) ? wp_get_post_terms( $id, $cat_tax, array( 'fields' => 'ids' ) ) : array();
		$tags       = taxonomy_exists( $tag_tax ) ? wp_get_post_terms( $id, $tag_tax, array( 'fields' => 'ids' ) ) : array();
		$outline    = json_decode( (string) $row['outline'], true );
		$years      = json_decode( (string) $row['years_mentioned'], true );

		if ( $this->compact ) {
			$item = array(
				'id'                  => $id,
				'title'               => $this->title( $id ),
				'url'                 => $row['url'],
				'status'              => 'publish' === $row['status'] ? null : $row['status'],
				'published'           => $row['published_at'] ? substr( (string) $row['published_at'], 0, 10 ) : null,
				'primary_category_id' => null !== $row['primary_term_id'] ? (int) $row['primary_term_id'] : null,
				'focus_keyword'       => $row['focus_keyword'],
				'words'               => (int) $row['word_count'],
				'links_in'            => (int) $row['internal_in'],
				'links_out'           => (int) $row['internal_out'],
				'years'               => is_array( $years ) ? $years : array(),
				'refresh_score'       => (int) $row['refresh_score'],
				'flags'               => $flags,
				'gsc'                 => null === $this->gsc ? null : $this->gsc_compact( $id ),
			);

			// Omit empty values; the compact contract says missing means empty/zero.
			return array_filter(
				$item,
				static fn( $v, $k ) => in_array( $k, array( 'id', 'title', 'url' ), true ) || ( null !== $v && '' !== $v && array() !== $v && 0 !== $v ),
				ARRAY_FILTER_USE_BOTH
			);
		}

		return array(
			'id'                  => $id,
			'title'               => $this->title( $id ),
			'slug'                => rawurldecode( (string) get_post_field( 'post_name', $id ) ),
			'url'                 => $row['url'],
			'status'              => $row['status'],
			'published_at'        => self::iso( $row['published_at'] ),
			'modified_at'         => self::iso( $row['modified_at'] ),
			'primary_category_id' => null !== $row['primary_term_id'] ? (int) $row['primary_term_id'] : null,
			'category_ids'        => is_array( $categories ) ? array_map( 'intval', $categories ) : array(),
			'tag_ids'             => is_array( $tags ) ? array_map( 'intval', $tags ) : array(),
			'seo'                 => array(
				'focus_keyword'    => $row['focus_keyword'],
				'seo_title'        => $row['seo_title'],
				'meta_description' => $row['meta_description'],
				'cornerstone'      => (bool) (int) $row['is_cornerstone'],
				'noindex'          => (bool) (int) $row['is_noindex'],
				'canonical'        => $row['canonical'],
			),
			'content_stats'       => array(
				'word_count'           => (int) $row['word_count'],
				'h2_count'             => (int) $row['h2_count'],
				'outline'              => is_array( $outline ) ? $outline : array(),
				'excerpt'              => (string) $row['excerpt'],
				'years_mentioned'      => is_array( $years ) ? $years : array(),
				'has_direct_answer'    => (bool) (int) $row['has_direct_answer'],
				'has_featured_image'   => (bool) (int) $row['has_featured_image'],
				'featured_image_has_alt' => (bool) (int) $row['featured_alt_ok'],
				'inline_images'        => (int) $row['inline_images'],
				'inline_images_no_alt' => (int) $row['inline_images_no_alt'],
			),
			'links_summary'       => array(
				'internal_out' => (int) $row['internal_out'],
				'internal_in'  => (int) $row['internal_in'],
				'menu_in'      => (int) $row['menu_in'],
				'external_out' => (int) $row['external_out'],
			),
			'refresh_score'       => (int) $row['refresh_score'],
			'flags'               => $flags,
		) + ( null === $this->gsc ? array() : array( 'search_console' => $this->gsc_item( $id ) ) );
	}

	/**
	 * Search Console metrics of one item (zeros when it had no impressions).
	 *
	 * @param int $id Object ID.
	 */
	private function gsc_item( int $id ): array {
		$m = $this->gsc[ $id ] ?? null;
		if ( null === $m ) {
			return array(
				'clicks'      => 0,
				'impressions' => 0,
			);
		}

		$item = array(
			'clicks'      => $m['clicks'],
			'impressions' => $m['impressions'],
			'ctr'         => $m['ctr'],
			'position'    => $m['position'],
		);
		if ( null !== $m['prev_clicks'] ) {
			$item['prev_clicks']   = $m['prev_clicks'];
			$item['prev_position'] = $m['prev_position'];
		}

		return $item;
	}

	/**
	 * Compact Search Console metrics: [clicks, impressions, position] or null without impressions.
	 *
	 * @param int $id Object ID.
	 */
	private function gsc_compact( int $id ): ?array {
		$m = $this->gsc[ $id ] ?? null;

		return null === $m ? null : array( $m['clicks'], $m['impressions'], $m['position'] );
	}

	/**
	 * Top-level Search Console section: period, totals, top queries and unmatched URLs.
	 */
	private function search_console_section(): array {
		$import  = GscRepository::latest_import();
		$summary = $import['summary'] ?? array();
		$queries = GscRepository::queries( $this->compact ? 100 : 200 )['items'];

		$unmatched = array();
		foreach ( GscRepository::unmatched( 50 ) as $row ) {
			if ( $row['clicks'] < 1 && $row['impressions'] < 50 ) {
				continue;
			}
			$unmatched[] = array(
				'url'         => $row['item'],
				'state'       => $row['match_state'],
				'clicks'      => $row['clicks'],
				'impressions' => $row['impressions'],
			);
		}

		return array(
			'source'          => 'csv_import',
			'imported_at'     => self::iso( $import['created_at'] ?? null ),
			'period'          => $summary['period'] ?? null,
			'compare'         => (bool) ( $summary['compare'] ?? false ),
			'totals'          => array(
				'clicks'      => (int) ( $summary['clicks'] ?? 0 ),
				'impressions' => (int) ( $summary['impressions'] ?? 0 ),
			),
			'rows_capped'     => ! empty( $summary['pages_capped'] ) || ! empty( $summary['queries_capped'] ),
			'top_queries'     => array_map(
				fn( $q ) => $this->compact
					? array( $q['item'], $q['clicks'], $q['impressions'], $q['position'] )
					: array(
						'query'       => $q['item'],
						'clicks'      => $q['clicks'],
						'impressions' => $q['impressions'],
						'position'    => $q['position'],
					),
				$queries
			),
			'unmatched_pages' => $unmatched,
			'notes'           => 'Metrics come from a Search Console Performance export (top rows only). ' . ( $this->compact ? 'Compact: item gsc = [clicks, impressions, position]; top_queries = [query, clicks, impressions, position].' : '' ),
		);
	}

	/**
	 * Categories, tags and product categories.
	 */
	private function taxonomies(): array {
		$out = array();
		$map = array(
			'categories'         => 'category',
			'tags'               => 'post_tag',
			'product_categories' => 'product_cat',
			'product_tags'       => 'product_tag',
		);
		$notes = \PaydarWP\PaydarPress\Profile\TaxonomyMap::notes();

		foreach ( $map as $key => $taxonomy ) {
			if ( ! taxonomy_exists( $taxonomy ) ) {
				continue;
			}
			$terms = get_terms( array( 'taxonomy' => $taxonomy, 'hide_empty' => false, 'number' => 0 ) );
			$list  = array();
			foreach ( is_array( $terms ) ? $terms : array() as $term ) {
				$link  = get_term_link( $term );
				$entry = array(
					'id'    => (int) $term->term_id,
					'name'  => html_entity_decode( $term->name, ENT_QUOTES, 'UTF-8' ),
					'slug'  => rawurldecode( $term->slug ),
					'count' => (int) $term->count,
					'url'   => is_string( $link ) ? $link : '',
				);
				if ( is_taxonomy_hierarchical( $taxonomy ) ) {
					$entry['parent']          = (int) $term->parent;
					$entry['has_description'] = mb_strlen( trim( wp_strip_all_tags( $term->description ) ) ) >= 50;
				}
				// Owner's notes from the taxonomy map (role: high|normal|low|nav|retired).
				$n             = $notes[ (int) $term->term_id ] ?? array();
				$entry['role'] = \PaydarWP\PaydarPress\Profile\TaxonomyMap::role_of( $n );
				if ( '' !== (string) ( $n['scope'] ?? '' ) ) {
					$entry['scope'] = (string) $n['scope'];
				}
				$list[] = $entry;
			}
			$out[ $key ] = $list;
		}

		return $out;
	}

	/**
	 * Site-level warnings: site findings and profile completeness.
	 *
	 * @param array $completion Completion.
	 */
	private function warnings( array $completion ): array {
		global $wpdb;

		$warnings = array();
		$table    = Schema::table( 'audit_findings' );
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = $wpdb->get_results( "SELECT code, data FROM {$table} WHERE object_kind = 'site' AND state IN ('open', 'reviewed')", ARRAY_A );

		foreach ( (array) $rows as $row ) {
			$data       = json_decode( (string) $row['data'], true );
			$warnings[] = array(
				'code' => $row['code'],
				'data' => is_array( $data ) ? $data : null,
			);
		}

		if ( array() !== $completion['missing'] ) {
			$warnings[] = array(
				'code'    => 'PROFILE_INCOMPLETE',
				'message' => 'برخی فیلدهای پروفایل سایت تکمیل یا تأیید نشده‌اند.',
				'fields'  => $completion['missing'],
			);
		}

		return $warnings;
	}

	/**
	 * Inventory rows.
	 *
	 * @param string[] $statuses Statuses.
	 */
	private function rows( array $statuses ): array {
		global $wpdb;

		$table = Schema::table( 'inventory' );
		$in    = implode( ',', array_map( static fn( $s ) => "'" . esc_sql( $s ) . "'", $statuses ) );

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = $wpdb->get_results( "SELECT * FROM {$table} WHERE status IN ({$in}) ORDER BY object_type, object_id", ARRAY_A );

		return is_array( $rows ) ? $rows : array();
	}

	/**
	 * Open finding codes per content ID.
	 *
	 * @return array<int, string[]>
	 */
	private function flags(): array {
		global $wpdb;

		$table = Schema::table( 'audit_findings' );
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = $wpdb->get_results( "SELECT object_id, code FROM {$table} WHERE object_kind = 'content' AND state = 'open'", ARRAY_A );

		$flags = array();
		foreach ( (array) $rows as $row ) {
			$flags[ (int) $row['object_id'] ][] = $row['code'];
		}

		return $flags;
	}

	/**
	 * Page IDs in the primary menu.
	 *
	 * @return array<int, true>
	 */
	private function main_menu_page_ids(): array {
		$menu = MenuScanner::primary_menu_id();
		$ids  = array();

		if ( null !== $menu ) {
			foreach ( (array) wp_get_nav_menu_items( $menu ) as $item ) {
				$ids[ (int) $item->object_id ] = true;
			}
		}

		return $ids;
	}

	/**
	 * Decoded title.
	 *
	 * @param int $id Post ID.
	 */
	private function title( int $id ): string {
		return html_entity_decode( get_the_title( $id ), ENT_QUOTES, 'UTF-8' );
	}

	/**
	 * GMT datetime → ISO 8601 in the site timezone.
	 *
	 * @param mixed $datetime GMT datetime.
	 */
	private static function iso( $datetime ): ?string {
		if ( empty( $datetime ) ) {
			return null;
		}

		return wp_date( 'c', (int) strtotime( $datetime . ' UTC' ) );
	}
